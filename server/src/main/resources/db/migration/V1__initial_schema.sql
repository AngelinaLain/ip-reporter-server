CREATE TABLE machines (
    device_id VARCHAR(128) PRIMARY KEY,
    hostname VARCHAR(255) NOT NULL,
    os VARCHAR(64) NOT NULL,
    agent_version VARCHAR(64) NOT NULL,
    last_seen TIMESTAMP WITH TIME ZONE NOT NULL,
    peer_ip VARCHAR(64) NOT NULL,
    snapshot TEXT NOT NULL
);
CREATE INDEX idx_machine_last_seen ON machines(last_seen);
CREATE TABLE dns_providers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    type VARCHAR(32) NOT NULL,
    access_key_id VARCHAR(512) NOT NULL,
    encrypted_secret TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE ddns_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    machine_device_id VARCHAR(128) NOT NULL REFERENCES machines(device_id),
    interface_id VARCHAR(256) NOT NULL,
    interface_name VARCHAR(256) NOT NULL,
    record_type VARCHAR(8) NOT NULL,
    provider_id BIGINT NOT NULL REFERENCES dns_providers(id),
    domain VARCHAR(253) NOT NULL,
    rr VARCHAR(253) NOT NULL,
    ttl INTEGER NOT NULL,
    line VARCHAR(128) NOT NULL,
    record_id VARCHAR(128) NOT NULL,
    address_mode VARCHAR(16) NOT NULL,
    specific_address VARCHAR(64) NOT NULL,
    allow_private BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    last_status VARCHAR(32),
    last_message VARCHAR(512),
    last_address VARCHAR(64),
    last_sync_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_ddns_target UNIQUE(provider_id, domain, rr, record_type, line)
);
CREATE TABLE ddns_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT,
    rule_name VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL,
    action VARCHAR(32) NOT NULL,
    address VARCHAR(64),
    message VARCHAR(512) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_ddns_log_time ON ddns_logs(created_at);
